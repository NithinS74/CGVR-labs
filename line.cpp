// 1. Epoxy MUST be included first
#include <epoxy/gl.h>

// 2. Prevent GLFW from including standard GL headers
#define GLFW_INCLUDE_NONE
#include <GLFW/glfw3.h>

// 3. C++ Standard Library headers
#include <cmath>
#include <iostream>
#include <vector>

struct Pixel {
  int x;
  int y;
};

// Generalized Bresenham's Line Algorithm (Handles all 8 octants/slopes)
std::vector<Pixel> generateBresenhamLine(int x0, int y0, int x1, int y1) {
  std::vector<Pixel> pixels;

  int dx = std::abs(x1 - x0);
  int dy = std::abs(y1 - y0);

  int sx = (x0 < x1) ? 1 : -1;
  int sy = (y0 < y1) ? 1 : -1;

  int err = dx - dy;

  while (true) {
    pixels.push_back({x0, y0});

    if (x0 == x1 && y0 == y1)
      break;

    int e2 = 2 * err;
    if (e2 > -dy) {
      err -= dy;
      x0 += sx;
    }
    if (e2 < dx) {
      err += dx;
      x0 += sy;
    }
  }

  return pixels;
}

// Simple Shader Sources
const char *vertexShaderSource = R"(
#version 330 core
layout (location = 0) in vec2 aPos;

void main() {
    gl_Position = vec4(aPos, 0.0, 1.0);
}
)";

const char *fragmentShaderSource = R"(
#version 330 core
out vec4 FragColor;

void main() {
    FragColor = vec4(0.2, 0.8, 1.0, 1.0); // Cyan color
}
)";

GLuint compileShader(GLenum type, const char *source) {
  GLuint shader = glCreateShader(type);
  glShaderSource(shader, 1, &source, NULL);
  glCompileShader(shader);

  GLint success;
  glGetShaderiv(shader, GL_COMPILE_STATUS, &success);
  if (!success) {
    char infoLog[512];
    glGetShaderInfoLog(shader, 512, NULL, infoLog);
    std::cerr << "Shader Compilation Error:\n" << infoLog << std::endl;
  }
  return shader;
}

GLuint createProgram(const char *vertSrc, const char *fragSrc) {
  GLuint vert = compileShader(GL_VERTEX_SHADER, vertSrc);
  GLuint frag = compileShader(GL_FRAGMENT_SHADER, fragSrc);

  GLuint program = glCreateProgram();
  glAttachShader(program, vert);
  glAttachShader(program, frag);
  glLinkProgram(program);

  glDeleteShader(vert);
  glDeleteShader(frag);
  return program;
}

int main() {
  const int WIDTH = 800;
  const int HEIGHT = 600;

  if (!glfwInit()) {
    std::cerr << "Failed to initialize GLFW" << std::endl;
    return -1;
  }

  glfwWindowHint(GLFW_CONTEXT_VERSION_MAJOR, 3);
  glfwWindowHint(GLFW_CONTEXT_VERSION_MINOR, 3);
  glfwWindowHint(GLFW_OPENGL_PROFILE, GLFW_OPENGL_CORE_PROFILE);

  GLFWwindow *window =
      glfwCreateWindow(WIDTH, HEIGHT, "Bresenham Line (OpenGL)", NULL, NULL);
  if (!window) {
    std::cerr << "Failed to create GLFW window" << std::endl;
    glfwTerminate();
    return -1;
  }

  glfwMakeContextCurrent(window);

  // 1. Calculate discrete pixel grid points using Bresenham's algorithm
  int x0 = 50, y0 = 50;
  int x1 = 750, y1 = 520;
  std::vector<Pixel> linePixels = generateBresenhamLine(x0, y0, x1, y1);

  // 2. Convert pixel coordinates to OpenGL NDC coordinates [-1.0, 1.0]
  std::vector<float> ndcVertices;
  for (const auto &p : linePixels) {
    float ndcX = (2.0f * p.x) / WIDTH - 1.0f;
    float ndcY = (2.0f * p.y) / HEIGHT - 1.0f;
    ndcVertices.push_back(ndcX);
    ndcVertices.push_back(ndcY);
  }

  // 3. Setup VAO / VBO
  GLuint VAO, VBO;
  glGenVertexArrays(1, &VAO);
  glGenBuffers(1, &VBO);

  glBindVertexArray(VAO);
  glBindBuffer(GL_ARRAY_BUFFER, VBO);
  glBufferData(GL_ARRAY_BUFFER, ndcVertices.size() * sizeof(float),
               ndcVertices.data(), GL_STATIC_DRAW);

  glVertexAttribPointer(0, 2, GL_FLOAT, GL_FALSE, 2 * sizeof(float), (void *)0);
  glEnableVertexAttribArray(0);

  GLuint shaderProgram =
      createProgram(vertexShaderSource, fragmentShaderSource);

  // Adjust point size to make pixels easily visible
  glPointSize(3.0f);

  // Render loop
  while (!glfwWindowShouldClose(window)) {
    glClearColor(0.05f, 0.05f, 0.08f, 1.0f);
    glClear(GL_COLOR_BUFFER_BIT);

    glUseProgram(shaderProgram);
    glBindVertexArray(VAO);

    // Draw individual pixel points generated by Bresenham
    glDrawArrays(GL_POINTS, 0, linePixels.size());

    glfwSwapBuffers(window);
    glfwPollEvents();
  }

  // Cleanup
  glDeleteVertexArrays(1, &VAO);
  glDeleteBuffers(1, &VBO);
  glDeleteProgram(shaderProgram);

  glfwDestroyWindow(window);
  glfwTerminate();
  return 0;
}
